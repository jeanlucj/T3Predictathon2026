#!/bin/bash
#SBATCH --job-name=t3multi
#SBATCH --partition=ceres
#SBATCH --nodes=1                    # ONE node: every worker shares one SQLite store
#SBATCH --ntasks=32
#SBATCH --mem=1800G
#SBATCH --time=21-00:00:00           # submit_multiple.local.sh overrides it and is the single
                                     # place the wall clock is declared
#SBATCH --account=CHANGEME
#SBATCH --output=logs/slurm-%j.out
#SBATCH --error=logs/slurm-%j.err
#
# Several optimization targets in sequence, each followed by its own held-out test, inside ONE
# allocation. See RUNBOOK_SLURM.md section 6 "Several domains in one job".
#
# For each row of multiple_settings.R, in order:
#
#   1. launch N workers with OPTIMIZER_DOMAIN_SETTINGS set to that row's settings file
#   2. let them run for that row's `days`
#   3. touch the stop file, wait for every worker to finish its evaluation and exit
#   4. run dev/holdout_test.R on that row's holdouts, against the same settings file
#
# Why one job and not six. The store and the cache are shared: every evaluation lands in the
# same evals.sqlite and each run reads only its own domain and scheme slice of it, while the
# ~11,000-file dosage cache is restored once instead of six times. The settings also differ
# only in run-identifying keys, so nothing about step 1 changes between rows except one
# environment variable.
#
# DO NOT EDIT THIS FILE to set your account, paths or sizing -- it is tracked, so local edits
# conflict on every `git pull`. Those values belong in submit_multiple.local.sh, which is
# gitignored:
#
#   cp submit_multiple.local.sh.example submit_multiple.local.sh && chmod +x submit_multiple.local.sh
#   ./submit_multiple.local.sh
#
# STOPPING. Two files, because there are two things to stop:
#
#   state/STOP        stops the WORKERS. The driver uses it itself at the end of every window,
#                     so touching it by hand ends the current setting early -- and the driver
#                     then stops the plan rather than guessing that you meant only that one.
#   state/STOP_PLAN   stops the PLAN at the next boundary, letting the current setting and its
#                     holdout test finish. This is the graceful one.
#
# scancel is the third option and loses only the evaluations in flight (median 29 min each).

set -euo pipefail

# ---- paths: supplied, never invented --------------------------------------
: "${OPTIMIZER_HOME:?not set -- submit through container/submit_multiple.local.sh}"
: "${REPO:?not set -- submit through container/submit_multiple.local.sh}"
export OPTIMIZER_HOME

SIF="${SIF:-$REPO/container/optimizer.sif}"
N_WORKERS="${N_WORKERS:-22}"
N_THREADS="${N_THREADS:-1}"
# The plan. A path, absolute or relative to the repo; the default is the usual copy.
MULTIPLE_SETTINGS="${MULTIPLE_SETTINGS:-$REPO/multiple_settings.R}"
# Holdout sizing and arguments. Defaults to the optimizer's own worker count: it is the same
# allocation and a holdout copy runs the same run_pipeline, so the same memory arithmetic holds.
HOLD_WORKERS="${HOLD_WORKERS:-$N_WORKERS}"
HOLD_THREADS="${HOLD_THREADS:-$N_THREADS}"
HOLD_EXTRA="${HOLD_EXTRA:-}"
# Skip every holdout test and only optimize. For a plan you intend to test separately with
# container/submit_holdout.sh, which can run beside the next setting instead of after it.
MULTI_SKIP_HOLDOUT="${MULTI_SKIP_HOLDOUT:-0}"
# How much of the wall clock to keep back for a holdout test, and the shortest optimization
# window worth starting. Both in hours. The reserve matches --time in submit_holdout.sh.
HOLDOUT_RESERVE_HOURS="${HOLDOUT_RESERVE_HOURS:-24}"
MULTI_MIN_OPT_HOURS="${MULTI_MIN_OPT_HOURS:-2}"
# How often the driver wakes during a window to look for a stop file or dead workers.
POLL_SECONDS="${POLL_SECONDS:-30}"

# apptainer is NOT on PATH by default on Ceres, and a batch shell may not define `module`.
# Before anything expensive: a job that queued for days must not die on "command not found".
. "$REPO/container/lib_apptainer.sh"
ensure_apptainer || exit 1

# The live store must be on node-local disk: SQLite's WAL coordinates through an mmap'd -shm
# file that network filesystems do not provide. Unset TMPDIR, or no SLURM_JOB_ID, means this is
# not inside a job -- and then $TMPDIR is shared storage, the one configuration that corrupts
# the store.
: "${TMPDIR:?TMPDIR is unset -- not inside a SLURM job? The store MUST be on node-local disk}"
: "${SLURM_JOB_ID:?SLURM_JOB_ID is unset -- this must run as a SLURM job, not on a login node}"

mkdir -p "$OPTIMIZER_HOME/state" "$OPTIMIZER_HOME/logs"

# $TMPDIR on Ceres is /tmp -- node-local but NOT per-job -- so a node this user has run on
# before still holds that job's store. Start clean: the leader restores the durable backup
# anyway, and backup_store() runs after every evaluation, so the node-local copy holds nothing
# the backup lacks. All three files, because WAL keeps committed rows in the sidecar.
BACKUP="$OPTIMIZER_HOME/state/evals_backup.sqlite"
STORE="$TMPDIR/t3opt_$(id -un)/evals.sqlite"
mkdir -p "$(dirname "$STORE")"
if [ -e "$STORE" ]; then
  echo "store     : removing a previous job's store on this node ($STORE)"
  rm -f "$STORE" "$STORE-wal" "$STORE-shm"
fi

echo "node      : $(hostname)"
echo "TMPDIR    : $TMPDIR"
echo "home      : $OPTIMIZER_HOME"
echo "image     : $SIF"
echo "store     : $STORE"
echo "plan      : $MULTIPLE_SETTINGS"
echo "workers   : $N_WORKERS x $N_THREADS threads   (holdout: $HOLD_WORKERS x $HOLD_THREADS)"
echo "build     : $(sed -n 's/^OPTIMIZER_BUILD *<- *"\(.*\)".*/\1/p' "$REPO/settings.R" 2>/dev/null || echo '?')"
if [ -f "$BACKUP" ]; then
  echo "backup    : $BACKUP ($(sqlite3 "$BACKUP" 'SELECT COUNT(*) FROM evals;' 2>/dev/null || echo '?') rows, merged by the leader)"
else
  echo "no backup at $BACKUP -- starting from an EMPTY store"
fi

# ---- run things inside the image ------------------------------------------
# One definition, used for the plan, the workers and the holdouts. The cd into $REPO is
# load-bearing: R reads .Renviron -- and so the T3 credentials -- from the working directory
# only. Each bind maps a path onto itself so the paths settings.R computes stay valid inside.
in_container() {
  apptainer exec \
    --bind "$REPO:$REPO" \
    --bind "$OPTIMIZER_HOME:$OPTIMIZER_HOME" \
    --bind "$TMPDIR:$TMPDIR" \
    "$SIF" \
    bash -c "cd '$REPO' && $1"
}

# ---- the stop file, asked of R rather than guessed ------------------------
# settings.local.R may override stop_file, and OPTIMIZER_HOME is set in .Renviron, which only R
# reads. Reconstructing the path out here would be wrong on exactly the machines that matter --
# and touching the wrong file means the driver believes it stopped a setting that is still
# going. tools/optimizer_paths.sh prints KEY=VALUE when executed; ask it once, inside the image
# where R has its packages.
PATHS="$(in_container "bash ./tools/optimizer_paths.sh" 2>/dev/null || true)"
STOP_FILE="$(printf '%s\n' "$PATHS" | sed -n 's/^STOP_FILE=//p' | head -1)"
case "${STOP_FILE:-}" in
  /*) : ;;
  *)  echo "could not resolve the stop file from R inside the image (got '${STOP_FILE:-}')." >&2
      echo "  check: apptainer exec $SIF bash -c \"cd '$REPO' && bash ./tools/optimizer_paths.sh\"" >&2
      exit 1 ;;
esac
STOP_PLAN="$(dirname "$STOP_FILE")/STOP_PLAN"
echo "stop file : $STOP_FILE"
echo "stop plan : $STOP_PLAN"
# Either file left behind by a previous job would halt this one before its first evaluation.
rm -f "$STOP_FILE" "$STOP_PLAN"

# ---- the plan: validated before a single evaluation runs ------------------
# --check first, so the log opens with the sequence and the wall-clock arithmetic. Then the TSV.
# Both can fail, and failing here costs nothing; failing on day four costs the allocation.
echo
echo "================ plan ================"
in_container "Rscript tools/plan_multiple.R --file='$MULTIPLE_SETTINGS' --check" || {
  echo "the plan is not valid -- nothing was run. Fix multiple_settings.R and resubmit." >&2
  exit 1
}
PLAN_TSV="$TMPDIR/t3multi_plan_${SLURM_JOB_ID}.tsv"
in_container "Rscript tools/plan_multiple.R --file='$MULTIPLE_SETTINGS'" > "$PLAN_TSV"
N_SET="$(wc -l < "$PLAN_TSV" | tr -d ' ')"
echo "======================================"
echo

# ---- how much wall clock is left ------------------------------------------
# SLURM_JOB_END_TIME is an epoch and is the cheap path; scontrol is the fallback. Empty means
# unknown, and then the driver runs the plan as written rather than refusing to start.
job_end_epoch() {
  if [ -n "${SLURM_JOB_END_TIME:-}" ]; then echo "$SLURM_JOB_END_TIME"; return; fi
  local e
  e="$(scontrol show job "$SLURM_JOB_ID" 2>/dev/null | tr ' ' '\n' | sed -n 's/^EndTime=//p' | head -1)"
  [ -n "$e" ] && date -d "$e" +%s 2>/dev/null || true
}
JOB_END="$(job_end_epoch)"
if [ -n "$JOB_END" ]; then
  echo "wall clock: job ends $(date -d "@$JOB_END" 2>/dev/null || echo "at epoch $JOB_END")"
else
  echo "wall clock: could not determine the job's end time -- the plan will run as written,"
  echo "            and a setting may be cut short by SLURM rather than by the driver."
fi

# ---- the window ------------------------------------------------------------
# Sleep in POLL_SECONDS steps rather than one long sleep, so a stop file takes effect in
# seconds and a worker crash is noticed rather than waited out.
#   0 = the window elapsed   1 = STOP_PLAN   2 = STOP (by hand)   3 = the workers exited
wait_window() {
  local secs="$1" deadline
  deadline=$(( $(date +%s) + secs ))
  while [ "$(date +%s)" -lt "$deadline" ]; do
    [ -f "$STOP_PLAN" ] && return 1
    [ -f "$STOP_FILE" ] && return 2
    kill -0 "$WPID" 2>/dev/null || return 3
    sleep "$POLL_SECONDS"
  done
  return 0
}

# ---- the sequence ----------------------------------------------------------
# idx is the setting being ATTEMPTED, n_done the number that ran. They differ whenever the plan
# stops before a setting rather than during one, and reporting the wrong one would say a setting
# ran that never started. (`n_done` and not `done`: that is a bash reserved word, and while an
# assignment to it happens to parse, nothing good comes of relying on that.)
idx=0
n_done=0
ABORT=""
while IFS=$'\t' read -r SETFILE DAYS HOLDOUTS; do
  [ -n "${SETFILE:-}" ] || continue
  idx=$(( idx + 1 ))

  if [ -f "$STOP_PLAN" ]; then
    ABORT="$STOP_PLAN appeared before setting $idx"; break
  fi

  WANT=$(awk -v d="$DAYS" 'BEGIN { printf "%d", d * 86400 }')
  RESERVE=0
  [ "$MULTI_SKIP_HOLDOUT" = "1" ] || RESERVE=$(( HOLDOUT_RESERVE_HOURS * 3600 ))
  MINOPT=$(( MULTI_MIN_OPT_HOURS * 3600 ))

  if [ -n "$JOB_END" ]; then
    REMAIN=$(( JOB_END - $(date +%s) ))
    if [ "$REMAIN" -lt $(( RESERVE + MINOPT )) ]; then
      # Minutes, not hours: integer hours report "0h left" with half an hour to go, which reads
      # like a bug in the clock rather than a deliberate stop.
      ABORT="$(( REMAIN / 60 )) min left before setting $idx, which is less than the ${HOLDOUT_RESERVE_HOURS}h holdout reserve plus a ${MULTI_MIN_OPT_HOURS}h minimum window"
      break
    fi
    if [ "$WANT" -gt $(( REMAIN - RESERVE )) ]; then
      echo "  window shortened: ${DAYS}d would overrun the allocation; using $(( (REMAIN - RESERVE) / 3600 ))h"
      WANT=$(( REMAIN - RESERVE ))
    fi
  fi

  echo
  echo "######## [$idx/$N_SET] $SETFILE"
  echo "         optimize for $(awk -v s="$WANT" 'BEGIN { printf "%.2f", s/86400 }') day(s), then hold out: $HOLDOUTS"
  echo "         started $(date)"

  # A stop file consumed by the previous setting would halt these workers immediately.
  # run_workers.sh clears a stale one itself, but only for worker 1; clear it here so the
  # intent is in one place.
  rm -f "$STOP_FILE"

  # Backgrounded so the driver keeps the clock. run_workers.sh ends in `wait`, so this returns
  # only when every worker has exited -- which is what makes step 3 below a real barrier.
  # The one thing that differs between settings: run_optimizer.R reads this and layers that
  # file over settings.local.R (read_domain_settings). Set inside the container's shell rather
  # than exported out here, so what reaches the workers is visible in this line.
  in_container "OPTIMIZER_DOMAIN_SETTINGS='$SETFILE' ./run_workers.sh $N_WORKERS $N_THREADS" &
  WPID=$!

  # `why=0; ... || why=$?` and not `; why=$?`: under `set -e` a simple command that returns
  # non-zero ends the script, and every interesting outcome of wait_window is non-zero.
  why=0; wait_window "$WANT" || why=$?

  case "$why" in
    0) echo "         window elapsed -- stopping workers" ;;
    1) echo "         $STOP_PLAN appeared -- stopping workers, then ending the plan" ;;
    2) echo "         $STOP_FILE was touched by hand -- stopping workers, then ending the plan" ;;
    3) echo "         ** the workers exited on their own, before the window was up --" \
            "check $OPTIMIZER_HOME/logs/run_w1.out. Holding out anyway: the store has" \
            "whatever they did finish. **" ;;
  esac

  # Step 3, the barrier: ask for a stop, then wait for every worker to finish the evaluation it
  # is inside. `wait` on a backgrounded apptainer returns its exit status; a worker that failed
  # is worth saying so about, but not worth abandoning the plan for -- the next setting is a
  # different domain and may be fine.
  touch "$STOP_FILE"
  if wait "$WPID"; then
    echo "         workers finished cleanly"
  else
    echo "         ** workers exited non-zero -- see $OPTIMIZER_HOME/logs/run_w*.out **"
  fi
  rm -f "$STOP_FILE"

  # Step 4, the measurement. Skipped when the plan was interrupted: a holdout test on a window
  # that was cut short measures something nobody asked for, and it would consume the hours the
  # interruption was meant to free.
  if [ "$MULTI_SKIP_HOLDOUT" = "1" ]; then
    echo "         holdout skipped (MULTI_SKIP_HOLDOUT=1). Run it with:"
    echo "           container/submit_holdout.sh -- --settings=$SETFILE --trials=$HOLDOUTS"
  elif [ "$why" = "1" ] || [ "$why" = "2" ]; then
    echo "         holdout skipped (the plan was interrupted). Run it with:"
    echo "           container/submit_holdout.sh -- --settings=$SETFILE --trials=$HOLDOUTS"
  else
    echo "         holdout test: $(date)"
    if in_container "./dev/run_holdout.sh $HOLD_WORKERS $HOLD_THREADS --settings='$SETFILE' --trials='$HOLDOUTS' $HOLD_EXTRA"; then
      echo "         holdout finished; read it with:"
      echo "           Rscript dev/holdout_test.R --settings=$SETFILE --report"
    else
      echo "         ** holdout FAILED -- see $OPTIMIZER_HOME/logs/holdout_*.out **"
    fi
  fi

  n_done=$(( n_done + 1 ))
  case "$why" in 1|2) ABORT="stopped by hand during setting $idx"; break ;; esac
done < "$PLAN_TSV"

echo
if [ -n "$ABORT" ]; then
  echo "plan ended early: $n_done of $N_SET setting(s) ran -- $ABORT"
else
  echo "plan complete: $n_done of $N_SET setting(s)"
fi
echo "finished $(date)"
rm -f "$STOP_PLAN"
